#!/usr/bin/env node
/**
 * Independent provably-fair verifier (ADR-003). Uses ONLY node:crypto: it shares no code with
 * packages/game-engine, so it can catch bugs in the engine's own SHA-256/HMAC/shuffle.
 *
 *   node scripts/verify-fairness.mjs shoe --server-seed <s> --client-seed <c> --nonce <n> [--cards 20] [--decks 6]
 *       Prints SHA-256(serverSeed) (compare with the hash shown before you played) and the
 *       order in which the round's cards come out of the shoe.
 *   node scripts/verify-fairness.mjs generate
 *       Prints the fixed test vectors (stdout) used by the engine's tests.
 *   node scripts/verify-fairness.mjs check <vectors.json>
 *       Recomputes a vectors file and exits non-zero on any difference (run in CI).
 */
import { createHash, createHmac } from 'node:crypto';
import { readFileSync } from 'node:fs';

const TWO_32 = 2 ** 32;

/** Byte stream: HMAC_SHA256(key=serverSeed, msg=`${clientSeed}:${nonce}:${cursor}`), cursor 0,1,... */
function stream(serverSeed, clientSeed, nonce) {
  let cursor = 0;
  let block = Buffer.alloc(0);
  let offset = 0;
  const nextByte = () => {
    if (offset >= block.length) {
      block = createHmac('sha256', serverSeed).update(`${clientSeed}:${nonce}:${cursor}`).digest();
      cursor++;
      offset = 0;
    }
    return block[offset++];
  };
  const nextUint32 = () =>
    nextByte() * 0x1000000 + nextByte() * 0x10000 + nextByte() * 0x100 + nextByte();
  const nextInt = (max) => {
    const limit = Math.floor(TWO_32 / max) * max; // reject the biased tail
    for (;;) {
      const x = nextUint32();
      if (x < limit) return x % max;
    }
  };
  return { nextUint32, nextInt };
}

function canonicalShoe(decks) {
  const cards = [];
  for (let d = 0; d < decks; d++)
    for (const suit of 'SHDC')
      for (const rank of ['A', '2', '3', '4', '5', '6', '7', '8', '9', 'T', 'J', 'Q', 'K'])
        cards.push(rank + suit);
  return cards;
}

/** Forward Fisher–Yates: for i = 0..n-2, j = i + nextInt(n - i), swap. */
function shuffledShoe(decks, rng) {
  const cards = canonicalShoe(decks);
  for (let i = 0; i < cards.length - 1; i++) {
    const j = i + rng.nextInt(cards.length - i);
    [cards[i], cards[j]] = [cards[j], cards[i]];
  }
  return cards;
}

const sha256 = (text) => createHash('sha256').update(text).digest('hex');

const CASES = [
  { serverSeed: 'server-seed-1', clientSeed: 'client-seed-1', nonce: 0 },
  { serverSeed: 'server-seed-1', clientSeed: 'client-seed-1', nonce: 1 },
  {
    serverSeed: '9f86d081884c7d659a2feaa0c55ad015a3bf4f1b2b0b822cd15d6c15b0f00a08',
    clientSeed: 'my lucky seed ñ €',
    nonce: 4242,
  },
  // A key longer than the SHA-256 block (64 bytes) exercises the HMAC key-hashing path.
  { serverSeed: 'k'.repeat(100), clientSeed: '', nonce: 9_007_199_254_740_991 },
];

const MAXES = [2, 52, 312, 3 * 2 ** 30];

function vectorFor({ serverSeed, clientSeed, nonce }) {
  const blocks = [0, 1, 2].map((cursor) =>
    createHmac('sha256', serverSeed).update(`${clientSeed}:${nonce}:${cursor}`).digest('hex'),
  );
  const u = stream(serverSeed, clientSeed, nonce);
  const uint32 = Array.from({ length: 10 }, () => u.nextUint32());
  const ints = MAXES.map((max) => {
    const s = stream(serverSeed, clientSeed, nonce);
    return { max, values: Array.from({ length: 12 }, () => s.nextInt(max)) };
  });
  return {
    serverSeed,
    clientSeed,
    nonce,
    serverSeedHash: sha256(serverSeed),
    blocks,
    uint32,
    ints,
    singleDeck: shuffledShoe(1, stream(serverSeed, clientSeed, nonce)),
    sixDeckFirst40: shuffledShoe(6, stream(serverSeed, clientSeed, nonce)).slice(0, 40),
  };
}

function generate() {
  return {
    scheme: 'hmac-sha256-v1',
    description:
      'Generated by scripts/verify-fairness.mjs with node:crypto. Each list starts from a fresh stream.',
    cases: CASES.map(vectorFor),
  };
}

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  if (i === -1) {
    if (fallback === undefined) throw new Error(`missing --${name}`);
    return fallback;
  }
  return process.argv[i + 1];
}

const command = process.argv[2];
if (command === 'generate') {
  process.stdout.write(`${JSON.stringify(generate(), null, 2)}\n`);
} else if (command === 'check') {
  const file = process.argv[3];
  const stored = JSON.parse(readFileSync(file, 'utf8'));
  let failures = 0;
  for (const c of stored.cases) {
    const fresh = vectorFor(c);
    if (JSON.stringify(fresh) !== JSON.stringify(c)) {
      failures++;
      console.error(`MISMATCH for case ${JSON.stringify({ ...c, nonce: c.nonce }).slice(0, 120)}…`);
    }
  }
  if (failures > 0) {
    console.error(`${failures} of ${stored.cases.length} vector(s) do not match node:crypto`);
    process.exit(1);
  }
  console.log(`OK: ${stored.cases.length} vectors match an independent node:crypto implementation`);
} else if (command === 'shoe') {
  const serverSeed = arg('server-seed');
  const clientSeed = arg('client-seed');
  const nonce = Number(arg('nonce'));
  const cards = Number(arg('cards', '20'));
  const decks = Number(arg('decks', '6'));
  const shoe = shuffledShoe(decks, stream(serverSeed, clientSeed, nonce));
  console.log(`serverSeedHash: ${sha256(serverSeed)}`);
  console.log(
    `first ${cards} cards (deal order: player, dealer up, player, dealer hole, then hits):`,
  );
  console.log(shoe.slice(0, cards).join(' '));
} else {
  console.error('usage: verify-fairness.mjs <shoe|generate|check> ... (see header)');
  process.exit(2);
}
